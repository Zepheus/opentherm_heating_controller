#!/usr/bin/env python3
"""Generate the BOM with cost estimates from the schematic.

Outputs (both committed, both regenerated after every schematic change):
  docs/bom/andiron-bom-jlc.csv   JLCPCB assembly upload format (Comment, Designator, Footprint, LCSC), fitted parts only
  docs/BOM.md                    human BOM: grouped lines, LCSC part, Basic/Preferred/Extended, unit price, line cost, totals, DNP list

Prices come from the local JLCPCB parts database that Konnect downloads (~/.konnect/jlcpcb.db, refresh it with the Konnect
tool download_jlcpcb_database). They are LCSC single-unit prices, so they over-estimate small passives bought in reels.
usage: python3 tools/bom.py [project_dir] [--boards N]
"""
import csv, io, os, sqlite3, subprocess, sys, datetime, re
from collections import OrderedDict

args = [a for a in sys.argv[1:] if not a.startswith("--")]
P = os.path.abspath(args[0] if args else os.path.join(os.path.dirname(__file__), ".."))
BOARDS = int(sys.argv[sys.argv.index("--boards") + 1]) if "--boards" in sys.argv else 5
CLI = os.environ.get("KICAD_CLI", "/Applications/KiCad/KiCad.app/Contents/MacOS/kicad-cli")
DB = os.path.expanduser(os.environ.get("JLC_DB", "~/.konnect/jlcpcb.db"))
EXT_FEE = float(os.environ.get("JLC_EXTENDED_FEE", "3.0"))   # USD per unique Extended part per order (JLC loading fee; check the quote)

import tempfile
tmp = os.path.join(tempfile.mkdtemp(), "bom.csv")
out = subprocess.run([CLI, "sch", "export", "bom", "--fields", "Reference,Value,Footprint,LCSC,${DNP}",
                      "--labels", "Reference,Value,Footprint,LCSC,DNP", "--group-by", "",
                      "-o", tmp, os.path.join(P, "heating-controller.kicad_sch")], capture_output=True, text=True)
rows = list(csv.DictReader(open(tmp))) if os.path.exists(tmp) else []
if not rows: sys.exit("BOM export failed:\n" + out.stderr)

db = sqlite3.connect(DB) if os.path.exists(DB) else None
def part(lcsc):
    if not db or not lcsc: return None
    r = db.execute("select MFR_Part, Manufacturer, Library_Type, Price, Stock from components where LCSC=?", (lcsc,)).fetchone()
    return dict(zip(("mpn", "mfr", "lib", "price", "stock"), r)) if r else None

def refkey(r): m = re.match(r"([A-Za-z]+)(\d+)", r); return (m.group(1), int(m.group(2))) if m else (r, 0)

fitted, dnp = OrderedDict(), []
for r in rows:
    ref = r["Reference"]
    if ref.startswith("#"): continue
    if (r.get("DNP") or "").strip(): dnp.append(r); continue
    # one line per orderable part: same LCSC number and footprint, whatever the schematic label says
    key = (r["LCSC"] or r["Value"], r["Footprint"])
    e = fitted.setdefault(key, {"refs": [], "values": []}); e["refs"].append(ref)
    if r["Value"] not in e["values"]: e["values"].append(r["Value"])

lines, total, ext_parts, missing = [], 0.0, set(), []
for (lcsc, fp), e in sorted(fitted.items(), key=lambda kv: refkey(sorted(kv[1]["refs"], key=refkey)[0])):
    refs = sorted(e["refs"], key=refkey); val = " / ".join(e["values"]); lcsc = lcsc if lcsc.startswith("C") and lcsc[1:].isdigit() else ""
    info = part(lcsc)
    if info is None: missing.append(lcsc or "/".join(refs))
    price = info["price"] if info else 0.0
    if info and info["lib"] == "Extended": ext_parts.add(lcsc)
    lines.append((refs, val, fp.split(":")[-1], lcsc, info, price, price * len(refs))); total += price * len(refs)

os.makedirs(os.path.join(P, "docs", "bom"), exist_ok=True)
with open(os.path.join(P, "docs", "bom", "andiron-bom-jlc.csv"), "w", newline="") as f:
    w = csv.writer(f); w.writerow(["Comment", "Designator", "Footprint", "LCSC"])
    for refs, val, fp, lcsc, *_ in lines: w.writerow([val, ",".join(refs), fp, lcsc])

db_date = datetime.date.fromtimestamp(os.path.getmtime(DB)).isoformat() if db else "n/a"
n_parts = sum(len(l[0]) for l in lines)
fees = EXT_FEE * len(ext_parts)
md = [f"# Andiron v1.0 — bill of materials",
      "",
      f"Generated by `tools/bom.py` from the schematic on {datetime.date.today().isoformat()}. "
      f"Prices: LCSC single-unit prices from the JLCPCB parts database snapshot of {db_date}; they are estimates, "
      "not a quote. Upload file for JLCPCB assembly: [`bom/andiron-bom-jlc.csv`](bom/andiron-bom-jlc.csv) "
      "(fitted parts only; the placement file comes from the board).",
      "",
      "## Cost summary",
      "",
      "| Item | USD |",
      "|---|---:|",
      f"| Components per board ({n_parts} placements, {len(lines)} unique parts) | {total:.2f} |",
      f"| Extended-part loading fees per order ({len(ext_parts)} × ${EXT_FEE:.2f}, assumed) | {fees:.2f} |",
      f"| **Components per board at {BOARDS} boards, fees included** | **{total + fees / BOARDS:.2f}** |",
      "",
      "PCB fabrication, assembly setup, through-hole soldering, stencil and shipping are not included; take them from the "
      "JLCPCB quote. The Library column is what the parts database reports; \"Preferred\" parts carry no loading fee on Economic assembly, so only \"Extended\" parts are counted. Swapping an Extended part for a Basic or Preferred equivalent saves its fee.",
      "",
      "## Fitted parts",
      "",
      "| Qty | References | Value | Footprint | LCSC | Manufacturer part | Library | Unit | Line |",
      "|---:|---|---|---|---|---|---|---:|---:|"]
for refs, val, fp, lcsc, info, price, cost in lines:
    lib = info["lib"] if info else "?"
    mpn = f'{info["mfr"]} {info["mpn"]}' if info else "not in database"
    link = f"[{lcsc}](https://jlcpcb.com/partdetail/{lcsc})" if lcsc else "—"
    md.append(f"| {len(refs)} | {', '.join(refs)} | {val} | {fp} | {link} | {mpn} | {lib} | {price:.4f} | {cost:.2f} |")
md += ["", "## Not fitted (DNP)", "", "| Reference | Value | Why it is on the board |", "|---|---|---|"]
why = {"R17": "OLED pin-order option", "R19": "OLED pin-order option",
       "R21": "OLED VCC option"}
for r in sorted(dnp, key=lambda r: refkey(r["Reference"])):
    md.append(f"| {r['Reference']} | {r['Value']} | {why.get(r['Reference'], 'option')} |")
if missing:
    md += ["", f"**Not found in the parts database:** {', '.join(missing)}. Refresh the database or fix the LCSC field."]
open(os.path.join(P, "docs", "BOM.md"), "w").write("\n".join(md) + "\n")
print(f"BOM: {len(lines)} lines, {n_parts} placements, ${total:.2f}/board components, {len(ext_parts)} extended, "
      f"${total + fees / BOARDS:.2f}/board at {BOARDS} incl. fees; DNP {len(dnp)}; missing {missing or 'none'}")
